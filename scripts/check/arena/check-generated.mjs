/* Holds the .generated. convention: a script under scripts/ writes the file, and the
 * name says so. Both directions fail silently otherwise -- an output without the infix
 * is read as hand-written by check:docs, and a payload file caught by an ignore pattern
 * ships a tag whose intro/styles.css @imports resolve to nothing, with no error. */

import { readFileSync, readdirSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { join, relative, sep } from 'node:path';
import { findComments } from '../../lib/arena/comments.mjs';
import { repoRoot as ROOT } from '../../lib/arena/repo-root.mjs';

const SCANNED_EXTENSIONS = ['.mjs', '.jsx', '.tsx', '.ts', '.js', '.css'];
const SKIPPED_DIRECTORIES = new Set(['node_modules', '.git', 'build', 'dist', '.cache']);

export const UNMARKED = {
  'intro/support.js':
    'generated by dc-runtime, whose source is not in this repository, so a clone cannot '
    + 'rebuild it. Not reproducible means never ignorable, and the infix would promise a '
    + '`bun run build` that cannot deliver it.',
  'assets/fonts/*.woff2':
    'downloaded from Google Fonts by scripts/generate/core/fetch-fonts.mjs. Binary, so it '
    + 'carries no header, and reproducing it needs the network. The one generated output '
    + 'identified by its generator rather than by its name.',
};

export const UNTRACKED = {
  'frameworks/react/vendor/*.generated.js':
    'a 975 KB CommonJS->ESM bundle of a devDependency, read only by the demo pages\' importmap.',
  'frameworks/react/components/**/*.generated.js':
    'the compiled sibling of a .jsx, read only by a demo page. The .jsx is the source a '
    + 'consumer copies.',
  'frameworks/react/ui-kits/**/*.generated.js':
    'the same, for the Delivery Console example app.',
  'frameworks/tailwind/Utilities.generated.css':
    'the compiled utility layer, read only by the specimen pages. An adopter imports '
    + 'frameworks/angular/theme/arena-tailwind.css and compiles their own.',
};

function walk(dir, root) {
  const found = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.')) continue;
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      if (SKIPPED_DIRECTORIES.has(entry.name)) continue;
      found.push(...walk(full, root));
    } else if (SCANNED_EXTENSIONS.some((e) => entry.name.endsWith(e))) {
      found.push(relative(root, full).split(sep).join('/'));
    }
  }
  return found;
}

function startsFile(source, comment) {
  return source.slice(0, source.indexOf(comment.text)).trim() === '';
}

export function claimsGeneration(source) {
  const [first] = findComments(source);
  return Boolean(first) && startsFile(source, first) && /GENERATED (by|from)/i.test(first.text);
}

export function unmarkedProblems(root = ROOT) {
  const problems = [];
  for (const rel of walk(root, root)) {
    if (rel.includes('.generated.')) continue;
    if (Object.hasOwn(UNMARKED, rel)) continue;
    if (claimsGeneration(readFileSync(join(root, rel), 'utf8'))) {
      problems.push(`${rel}: its header says a script writes it, but its name does not — rename it to *.generated.* or argue for it in UNMARKED`);
    }
  }
  return problems;
}

export function trackingProblems(root = ROOT, run = gitRun) {
  const tracked = new Set(run(['ls-files'], root));
  const problems = [];
  const claimed = new Set();

  for (const rel of walk(root, root)) {
    if (!rel.includes('.generated.')) continue;
    const pattern = run(['check-ignore', '--no-index', rel], root).length > 0;
    if (pattern) {
      const owner = Object.keys(UNTRACKED).find((p) => matches(p, rel));
      if (!owner) {
        problems.push(`${rel}: .gitignore hides it, but no UNTRACKED entry says why`);
        continue;
      }
      claimed.add(owner);
      if (tracked.has(rel)) problems.push(`${rel}: ignored by pattern yet still in the index — run git rm --cached`);
      continue;
    }
    if (!tracked.has(rel)) problems.push(`${rel}: neither tracked nor ignored — it would reach no clone and no tag`);
  }

  for (const pattern of Object.keys(UNTRACKED)) {
    if (!claimed.has(pattern)) problems.push(`UNTRACKED names ${pattern}, which matches nothing — a stale reason is worse than none`);
  }
  return problems;
}

export function matches(pattern, path) {
  const rx = pattern
    .split('**/').map((part) => part.replace(/[.+^${}()|[\]\\]/g, '\\$&').replace(/\*/g, '[^/]*'))
    .join('(?:.*/)?');
  return new RegExp(`^${rx}$`).test(path);
}

function gitRun(args, cwd) {
  const { stdout } = spawnSync('git', args, { cwd, encoding: 'utf8' });
  return (stdout ?? '').split('\n').filter(Boolean);
}

export function unmarkedCoverageProblems(root = ROOT, run = gitRun) {
  const tracked = run(['ls-files'], root);
  return Object.keys(UNMARKED)
    .filter((pattern) => !tracked.some((path) => matches(pattern, path)))
    .map((pattern) => `UNMARKED names ${pattern}, which matches no tracked file — drop the exception`);
}

function main() {
  const problems = [...unmarkedProblems(), ...trackingProblems(), ...unmarkedCoverageProblems()];
  if (problems.length > 0) {
    for (const problem of problems) console.error(`check-generated: ${problem}`);
    console.error(`\ncheck-generated: ${problems.length} problem(s)`);
    process.exit(1);
  }
  console.log(
    `check-generated: every generated file names itself; ${Object.keys(UNTRACKED).length} ignore pattern(s) `
    + `and ${Object.keys(UNMARKED).length} unmarked output(s) carry a reason`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
