/* Emits the playground into every framework layer from one source. The codec is copied
 * rather than reimplemented per layer, because two hand-written copies of decode() that
 * drift render the SAME url differently in each layer, which is the one failure this whole
 * arrangement exists to prevent, and no gate would see it: each layer would compile, each
 * suite would pass, and only a person comparing two pages would notice. */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { repoRoot as root } from '../../lib/arena/repo-root.mjs';

export const PLAYGROUND_LAYERS = ['react', 'angular'];

export const CODEC_SOURCE = 'frameworks/demos/PlaygroundCodec.ts';

export const CODEC_BANNER =
  '/* GENERATED by scripts/generate/arena/generate-playgrounds.mjs from frameworks/demos/PlaygroundCodec.ts.\n'
  + ' * Edit the source, not this copy: every layer carries the same bytes so the same URL cannot\n'
  + ' * resolve to two different views. */\n';

export function codecTarget(layer) {
  return join('frameworks', layer, 'playground', 'PlaygroundCodec.generated.ts');
}

export function renderCodec(source) {
  return `${CODEC_BANNER}\n${source}`;
}

export function codecFiles(base = root) {
  const source = readFileSync(join(base, CODEC_SOURCE), 'utf8');
  const body = renderCodec(source);
  return new Map(PLAYGROUND_LAYERS.map((layer) => [codecTarget(layer), body]));
}

export function buildPlaygrounds(base = root) {
  const files = codecFiles(base);
  const problems = [];
  if (files.size === 0) {
    problems.push('generate-playgrounds: emitted 0 files, and an empty emit is a failure rather than a clean pass');
  }
  return { files, problems };
}

function main() {
  const { files, problems } = buildPlaygrounds();
  if (problems.length > 0) {
    for (const problem of problems) console.error(problem);
    process.exit(1);
  }
  for (const [rel, body] of files) {
    const path = join(root, rel);
    if (!existsSync(dirname(path))) mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    console.log(`wrote ${rel}`);
  }
  console.log(`generate-playgrounds: ${files.size} file(s) emitted`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
