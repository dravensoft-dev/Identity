import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { basename, dirname, join } from 'node:path';
import { compileLayer, compileEntry, layerManifests } from '../../lib/tailwind/tailwind-compile.mjs';
import {
  classBase, classesManifest, entryStylesheet, stripIndirection, stripProblems, themeMapFor,
} from '../../lib/tailwind/component-css.mjs';
import {
  componentSheet, matchingBrace, preludeSheet, splitUtilities,
} from '../../lib/tailwind/component-sheets.mjs';
import { splitCompiledSheet } from '../../lib/tailwind/sheet-split.mjs';
import { repoRoot } from '../../lib/arena/repo-root.mjs';

type BuildOptions = { root?: string; manifests?: Map<string, any> };

export const BANNER = '/* GENERATED by scripts/build/tailwind/build-tailwind.ts — edit frameworks/tailwind/Theme.css or a manifest, not this file. */\n';

export function manifestBanner(jsonFile) {
  return `/* GENERATED by scripts/build/tailwind/build-tailwind.ts — edit ${jsonFile}, not this file. */\n`;
}

export function generatedPath(opts: BuildOptions = {}) {
  return join(opts.root ?? repoRoot, 'frameworks', 'tailwind', 'Utilities.generated.css');
}

export function buildTailwind(opts: BuildOptions = {}) {
  const { css } = compileLayer(opts);
  return BANNER + css;
}

export function manifestModule(manifest, jsonFile) {
  const { compoundVariants, ...rest } = manifest;
  if (!compoundVariants) {
    return `${manifestBanner(jsonFile)}export default ${JSON.stringify(manifest, null, 2)} as const;\n`;
  }
  const entries = compoundVariants.map((entry) => `${JSON.stringify(entry, null, 2)} as const`).join(',\n');
  return `${manifestBanner(jsonFile)}const compoundVariants = [\n${entries},\n];\n\n`
    + `export default { ...(${JSON.stringify(rest, null, 2)} as const), compoundVariants };\n`;
}

export const CONSUMING_LAYERS = ['react'];
export const CSS_CONSUMING_LAYERS = ['react', 'angular'];
export const CONSUME = 'frameworks/tailwind/consume';
export const PRELUDE = `${CONSUME}/Prelude.generated.css`;
export const BARREL = `${CONSUME}/Components.generated.css`;
export const PREFLIGHT = `${CONSUME}/Preflight.generated.css`;

export function sheetPath(manifestFile) {
  return manifestFile
    .replace('frameworks/tailwind/components/', `${CONSUME}/components/`)
    .replace(/\.manifest\.json$/, '.styles.generated.css');
}

export function keyframesIn(css) {
  const blocks = [];
  for (const match of css.matchAll(/@keyframes\s+[A-Za-z0-9_-]+\s*\{/g)) {
    const open = match.index + match[0].length - 1;
    const close = matchingBrace(css, open);
    if (close === -1) throw new Error('build-tailwind: an @keyframes block never closes');
    blocks.push(css.slice(match.index, close + 1));
  }
  return blocks;
}

export function keyframesOf(root) {
  const animations = readFileSync(join(root, 'frameworks/tailwind/Animations.css'), 'utf8');
  const blocks = keyframesIn(animations);
  if (blocks.length === 0) {
    throw new Error('build-tailwind: Animations.css declares no @keyframes, so every animation the '
      + 'component CSS names would resolve to nothing and simply not play');
  }
  return blocks.join('\n\n');
}

export function buildComponentCss(opts: BuildOptions = {}) {
  const root = opts.root ?? repoRoot;
  const manifests = opts.manifests ?? layerManifests(root);
  const preset = join(root, 'frameworks/tailwind/Theme.css');

  const raw = compileEntry(entryStylesheet(preset, manifests), root);
  const problems = stripProblems(raw, themeMapFor(root));
  if (problems.length > 0) {
    throw new Error(`build-tailwind: the compiled component CSS carries an indirection the preset does `
      + `not explain, so stripping it would guess:\n  ${problems.join('\n  ')}`);
  }

  const byComponent = new Map();
  for (const [file, manifest] of manifests) byComponent.set(classBase(manifest.component), file);

  const { shared, components } = splitUtilities(stripIndirection(raw), new Set(byComponent.keys()));
  const out = new Map();
  out.set(join(root, PRELUDE), BANNER + preludeSheet(shared, keyframesOf(root)));

  const sheets = [];
  for (const [name, rules] of components) {
    const file = byComponent.get(name);
    if (!file) throw new Error(`build-tailwind: ${name} has rules but no manifest to write them beside`);
    const rel = sheetPath(file);
    sheets.push(rel);
    out.set(join(root, rel), BANNER + componentSheet(rules, preludeSpecifier(rel)));
  }

  const imports = sheets.sort().map((rel) => `@import './${rel.replace(`${CONSUME}/`, '')}';`);
  const barrel = `${BANNER}@import './${basename(PREFLIGHT)}';\n`
    + `@import './${basename(PRELUDE)}';\n${imports.join('\n')}\n`;
  out.set(join(root, BARREL), barrel);
  out.set(join(root, PREFLIGHT), BANNER + splitCompiledSheet(readFileSync(generatedPath({ root }), 'utf8')).base);

  return out;
}

export function preludeSpecifier(rel) {
  const depth = rel.split('/').length - 1 - PRELUDE.split('/').length + 1;
  return `${'../'.repeat(depth)}${basename(PRELUDE)}`;
}

export function buildClassModules(opts: BuildOptions = {}) {
  const root = opts.root ?? repoRoot;
  const manifests = opts.manifests ?? layerManifests(root);
  const out = new Map();
  for (const [file, manifest] of manifests) {
    const rel = file.replace(/\.manifest\.json$/, '.classes.generated.ts');
    const body = `${manifestBanner(basename(file))}export default ${JSON.stringify(classesManifest(manifest), null, 2)} as const;\n`;
    out.set(join(root, rel), body);
    for (const layer of CSS_CONSUMING_LAYERS) {
      const mirrored = rel.replace('frameworks/tailwind/', `frameworks/${layer}/`);
      if (existsSync(dirname(join(root, mirrored)))) out.set(join(root, mirrored), body);
    }
  }
  return out;
}

export function buildStylesRuntime(opts: BuildOptions = {}) {
  const root = opts.root ?? repoRoot;
  const source = readFileSync(join(root, 'frameworks/tailwind/ArenaStyles.ts'), 'utf8');
  const out = new Map();
  for (const layer of CSS_CONSUMING_LAYERS) {
    out.set(join(root, `frameworks/${layer}/ArenaStyles.generated.ts`),
      manifestBanner('frameworks/tailwind/ArenaStyles.ts') + source);
  }
  return out;
}

export function consumerCopies(manifestFile, root) {
  return CONSUMING_LAYERS
    .map((layer) => manifestFile.replace('frameworks/tailwind/', `frameworks/${layer}/`))
    .filter((rel) => existsSync(dirname(join(root, rel))))
    .map((rel) => join(root, rel));
}

export function buildManifestModules(opts: BuildOptions = {}) {
  const { manifests } = compileLayer(opts);
  const root = opts.root ?? repoRoot;
  const out = new Map();
  for (const [file, manifest] of manifests) {
    const rel = file.replace(/\.json$/, '.generated.ts');
    const body = manifestModule(manifest, basename(file));
    out.set(join(root, rel), body);
    for (const copy of consumerCopies(rel, root)) out.set(copy, body);
  }
  return out;
}

export function buildRecipeRuntime(opts: BuildOptions = {}) {
  const root = opts.root ?? repoRoot;
  const source = readFileSync(join(root, 'frameworks/tailwind/Tv.ts'), 'utf8');
  const out = new Map();
  for (const layer of CONSUMING_LAYERS)
    out.set(join(root, `frameworks/${layer}/Tv.generated.ts`), manifestBanner('frameworks/tailwind/Tv.ts') + source);
  return out;
}

function main() {
  const text = buildTailwind();
  const path = generatedPath();
  writeFileSync(path, text);
  console.log(`build-tailwind: wrote ${path} (${text.length} bytes)`);

  const emitted = [
    ...buildManifestModules(), ...buildRecipeRuntime(),
    ...buildComponentCss(), ...buildClassModules(), ...buildStylesRuntime(),
  ];
  for (const [filePath, content] of emitted) {
    mkdirSync(dirname(filePath), { recursive: true });
    writeFileSync(filePath, content);
  }
  console.log(`build-tailwind: wrote ${emitted.length} generated file(s) into ${CONSUME}/ and beside the manifests`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
